def read_json(path):
    return json.loads(path.read_bytes())


def write_json(path, data):
    path.write_text(json.dumps(data, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def command(*args):
    return subprocess.check_output(args, text=True).strip()


def deb_owners():
    owners = {}
    for listing in Path("/var/lib/dpkg/info").glob("*.list"):
        for name in listing.read_text(encoding="utf-8").splitlines():
            owners.setdefault(name, listing.stem)
    return owners


@lru_cache(maxsize=None)
def deb_source(binary):
    result = command(
        "dpkg-query", "-W", "-f=${source:Package} ${source:Version}", binary,
    )
    return result.split()


def generated_cache(path):
    name = path.as_posix()
    if name.endswith("/gio/modules/giomodule.cache"):
        return "gio-querymodules"
    if name.startswith("/usr/share/icons/") and path.name == "icon-theme.cache":
        return "gtk-update-icon-cache"
    if name == "/usr/share/mime/mime.cache":
        return "update-mime-database"
    return None


def capture(toc, root, work):
    """Called from the PyInstaller spec before any files are transformed."""
    wheels, wheel_files = wheel_origins()
    owners = deb_owners()
    sources = {}
    components = {}
    notices = {}
    unknown = set()
    links = {}
    revision = command("git", "rev-parse", "HEAD")
    schemas = work / "_pyi_gschema_compilation"
    if schemas.is_dir():
        schema_inputs = []
        for path in schemas.iterdir():
            if path.name == "gschemas.compiled":
                continue
            original = Path("/usr/share/glib-2.0/schemas") / path.name
            if sha256(original) != sha256(path):
                raise ValueError(f"generated GLib schema input differs: {path.name}")
            schema_inputs.append((f"schema-input/{path.name}", str(original), "DATA"))
        toc = [*toc, *schema_inputs]
    for target, filename, kind in toc:
        if kind == "SYMLINK":
            destination = posixpath.normpath(posixpath.join(posixpath.dirname(target), filename))
            if destination.startswith(("/", "../")) or destination == "..":
                raise ValueError(f"PyInstaller symlink leaves the bundle: {target}")
            links[target] = filename
            continue
        if filename == "-":
            continue
        path = Path(filename).resolve(strict=True)
        if path.is_relative_to(work):
            continue  # generated bytecode, caches and schemas
        absolute = path.as_posix()
        owner = owners.get(absolute) or owners.get(absolute.removeprefix("/usr"))
        if path.is_relative_to(root) and ".venv" not in path.relative_to(root).parts:
            key = "project"
            origin = path.relative_to(root).as_posix()
            components[key] = ("project", revision)
        elif not owner and path in wheel_files:
            name, origin = wheel_files[path]
            key = name.replace("_", "-")
            components[key] = ("wheel", wheels[name][0]["version"])
        else:
            if not owner:
                # These caches come from the package-owned data and modules
                # in the TOC, which are covered by their Ubuntu sources.
                if generator := generated_cache(path):
                    key = "generated:" + generator
                    components[key] = ("generated", revision)
                    sources[target] = {"component": key, "source": generator, "sha256": sha256(path)}
                else:
                    unknown.add(absolute)
                continue
            origin = absolute
            name, version = deb_source(owner)
            key = "deb-" + name
            previous = components.setdefault(key, ("linux", version))
            if previous != ("linux", version):
                raise ValueError(f"multiple source revisions for {name}")
            package = owner.partition(":")[0]
            notice = Path("/usr/share/doc") / package / "copyright"
            if not notice.is_file():
                raise ValueError(f"no Ubuntu licence notice for {package}")
            notices[f"licenses/ubuntu/{package}/copyright"] = str(notice)
        sources[target] = {"component": key, "source": origin, "sha256": sha256(path)}
    if unknown:
        raise ValueError("unowned PyInstaller inputs: " + ", ".join(sorted(unknown)))
    write_json(work / "linux-inputs.json", {"components": components, "files": sources, "symlinks": links})
    return [(dest, path, "DATA") for dest, path in notices.items()]


def download(url, checksum, target):
    if not target.exists():
        with urlopen(url, timeout=120) as response, target.open("xb") as output:
            shutil.copyfileobj(response, output)
    if sha256(target) != checksum:
        raise ValueError(f"download checksum differs: {target.name}")
    return target


def wheel_sources(name, version, binary, folder):
    with urlopen(f"https://pypi.org/pypi/{name}/{version}/json", timeout=60) as response:
        files = json.load(response)["urls"]
    url = binary["url"]
    filename = Path(unquote(urlsplit(url).path)).name
    wheel = next(item for item in files if item["filename"] == filename)
    checksum = binary["archive_info"]["hashes"]["sha256"]
    if wheel["digests"]["sha256"] != checksum or wheel["url"] != url:
        raise ValueError(f"wheel differs from PyPI metadata: {filename}")
    path = download(url, checksum, folder / filename)
    sdist = next(item for item in files if item["packagetype"] == "sdist")
    source = download(sdist["url"], sdist["digests"]["sha256"], folder / sdist["filename"])
    return path, source


def flatpak_report(manifest):
    reports = []
    for module in manifest["modules"]:
        if module["name"] != "python3-pyhanko":
            continue
        for source in module["sources"]:
            if "x86_64" in source.get("only-arches", ["x86_64"]):
                reports.append({"url": source["url"], "archive_info": {"hashes": {"sha256": source["sha256"]}}})
    if not reports:
        raise ValueError("the Flatpak manifest has no wheel inputs")
    return reports


def project_archive(commit, destination):
    subprocess.run(["git", "archive", "--format=zip", "--output", str(destination), commit], check=True)


def vendored_sources(wheels, paths, folder, pool):
    inputs = []
    for name, (version, artifacts) in VENDORED.items():
        if wheels[name][0] != version:
            raise ValueError(f"the native source pins must be updated for {name}")
        inputs.extend(artifacts)
    _, crypto = paths["cryptography"]
    with tarfile.open(crypto) as source:
        member = next(item for item in source if item.name.endswith("/Cargo.lock"))
        packages = tomllib.loads(source.extractfile(member).read().decode("utf-8"))["package"]
    for package in packages:
        if "source" not in package:
            continue
        if package["source"] != "registry+https://github.com/rust-lang/crates.io-index":
            raise ValueError(f"unsupported Cargo source: {package['source']}")
        name, version = package["name"], package["version"]
        filename = f"{name}-{version}.crate"
        inputs.append((filename, f"https://static.crates.io/crates/{name}/{filename}", package["checksum"]))

    def fetch(item):
        name, url, checksum = item
        return download(url, checksum, folder / name)

    return list(pool.map(fetch, inputs))


def zip_inputs(destination, paths):
    if len({path.name for path in paths}) != len(paths):
        raise ValueError("duplicate source names")
    with ZipFile(destination, "x") as archive:
        for path in paths:
            archive.write(path, path.name)
    return {path.name: sha256(path) for path in paths}


def snapshot(args):
    """Use the signed Ubuntu source index and pinned PyPI downloads."""
    commit = command("git", "rev-parse", "HEAD")
    args.cache.mkdir()
    captured = read_json(args.inputs) if args.inputs else {"components": {}, "files": {}}
    manifest = read_json(args.manifest) if args.manifest else None
    reports = flatpak_report(manifest) if manifest else [
        item["download_info"] for item in read_json(args.pip_report)["install"]
    ]
    wheels = {}
    for report in reports:
        filename = Path(unquote(urlsplit(report["url"]).path)).name
        name, version, *_ = filename.split("-")
        wheels[name.replace("_", "-").lower()] = (version, report)

    def fetch_wheel(item):
        name, (version, report) = item
        return name, wheel_sources(name, version, report, args.cache)

    with ThreadPoolExecutor(max_workers=6) as pool:
        wheel_paths = dict(pool.map(fetch_wheel, wheels.items()))
        native = vendored_sources(wheels, wheel_paths, args.cache, pool)

    project = args.cache / "p7m-extractor-git.zip"
    project_archive(commit, project)
    metadata = {"commit": commit, "bundle": args.binary.name, "sha256": sha256(args.binary),
                "build_inputs": captured, "wheels": reports}
    if manifest:
        metadata.update({"sdk_commit": args.sdk, "runtime_commit": args.runtime})
        installed = next(args.bundle.glob("lib*/python*/site-packages"))
        for wheel, _ in wheel_paths.values():
            with ZipFile(wheel) as archive:
                for member in archive.infolist():
                    name = member.filename
                    if member.is_dir() or name.endswith(".dist-info/RECORD"):
                        continue
                    area, marker, rest = name.partition(".data/")
                    if marker:
                        category, _, relative = rest.partition("/")
                        destination = {"purelib": installed, "platlib": installed,
                                       "data": args.bundle}.get(category)
                        if destination is None:
                            raise ValueError(f"unrecognised wheel layout: {area}: {name}")
                        target = destination / relative
                    else:
                        target = installed / name
                    if target.read_bytes() != archive.read(member):
                        raise ValueError(f"Flatpak wheel member differs: {wheel.name}: {name}")
        paths = [
            path for path in (args.bundle / "share/p7m-extractor/p7m_extractor").rglob("*")
            if path.is_file() and path.suffix != ".pyc"
        ]
        with ZipFile(project) as source:
            expected = {entry.filename.removeprefix("src/p7m_extractor/") for entry in source.infolist()
                        if not entry.is_dir() and entry.filename.startswith("src/p7m_extractor/")}
            actual = {path.relative_to(args.bundle / "share/p7m-extractor/p7m_extractor").as_posix()
                      for path in paths}
            if actual != expected:
                raise ValueError("Flatpak application files differ from the Git archive")
            for path in paths:
                name = path.relative_to(args.bundle / "share/p7m-extractor/p7m_extractor").as_posix()
                if path.read_bytes() != source.read("src/p7m_extractor/" + name):
                    raise ValueError(f"Flatpak source differs from Git: {name}")
        metadata["flatpak_manifest"] = manifest
    else:
        with ZipFile(project) as source:
            for row in captured["files"].values():
                key = row["component"]
                kind, version = captured["components"][key]
                name = row["source"]
                if kind == "project" and not name.startswith("locale/"):
                    if digest(source.read(name)) != row["sha256"]:
                        raise ValueError(f"project build input differs from Git: {name}")
                if kind == "wheel" and not name.endswith(("/RECORD", "/REQUESTED", "/INSTALLER")):
                    if wheels[key][0] != version:
                        raise ValueError(f"wheel revision differs: {key}")
                    with ZipFile(wheel_paths[key][0]) as wheel:
                        if digest(wheel.read(name)) != row["sha256"]:
                            raise ValueError(f"portable input differs from its wheel: {key}: {name}")
        def fetch_ubuntu(item):
            key, version = item
            folder = args.cache / key
            folder.mkdir()
            subprocess.run(["apt-get", "source", "--download-only", f"{key.removeprefix('deb-')}={version}"],
                           cwd=folder, check=True)
            files = sorted(folder.iterdir())
            if len(files) < 2 or not any(path.suffix == ".dsc" for path in files):
                raise ValueError(f"Ubuntu source package incomplete: {key}")
            return key, {path.name: sha256(path) for path in files}

        ubuntu = [(key, version) for key, (kind, version) in captured["components"].items() if kind == "linux"]
        with ThreadPoolExecutor(max_workers=6) as pool:
            metadata["apt_sources"] = dict(pool.map(fetch_ubuntu, ubuntu))
    metadata_path = args.cache / "build-provenance.json"
    write_json(metadata_path, metadata)
    artifacts = [project, metadata_path, *native, *(source for _, source in wheel_paths.values())]
    artifacts.extend(path for folder in args.cache.glob("deb-*") if folder.is_dir() for path in folder.iterdir())
    sources = args.cache / "build-sources.zip"
    members = zip_inputs(sources, artifacts)
    platform = "flatpak" if manifest else "linux-x64"
    key = "linux:build"
    # The exported package digest is in the source member checked by the
    # release job, and the underlying staged files are sealed here.
    sealed = payload(args.bundle)
    files = [{"target": name, "component": key, "source": name, "sha256": checksum}
             for name, checksum in sealed.items()]
    notices = {name: checksum for name, checksum in sealed.items() if "/licenses/" in name}
    inventory = {"schema_version": 1, "platform": platform, "issues": [], "notices": notices,
                 "components": {key: {"kind": "linux", "name": "build", "version": commit}},
                 "files": files, "payload": sealed}
    receipts = {"schema_version": 1, "components": {key: {"version": commit, "source": sources.name,
                "source_sha256": sha256(sources), "build_inputs": sealed, "required_members": members}}}
    inventory_path = args.cache / "inventory.json"
    receipts_path = args.cache / "receipts.json"
    write_json(inventory_path, inventory)
    write_json(receipts_path, receipts)
    collect(args.bundle, inventory_path, receipts_path, args.output)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for option in ("bundle", "binary", "cache", "output"):
        parser.add_argument("--" + option, required=True, type=Path)
    parser.add_argument("--inputs", type=Path)
    parser.add_argument("--pip-report", type=Path)
    parser.add_argument("--manifest", type=Path)
    parser.add_argument("--sdk")
    parser.add_argument("--runtime")
    args = parser.parse_args()
    if args.manifest and not (args.sdk and args.runtime):
        parser.error("the Flatpak manifest requires exact SDK and runtime commits")
    if not args.manifest and not (args.inputs and args.pip_report):
        parser.error("the portable build requires the spec inputs and pip report")
    snapshot(args)


if __name__ == "__main__":
    main()
